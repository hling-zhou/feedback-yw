/**
 * 共享意图提取层 (Intent Extractor)
 *
 * 解决 requestSceneClassifier 与 problemTypeClassifier 各自独立决策、产出矛盾结果的问题。
 * 从 customerRequest 文本一次提取两个维度：
 *   - action (动作意图): 客户想让我们做什么 → 决定 requestScene
 *   - domain (问题域): 问题属于什么领域     → 决定 problemType
 *
 * 冲突消解原则：资源申请(申请+资源名词) > 故障排查 > 咨询 > 催办 > 其他
 *
 * 设计约束：
 *   - 纯函数，输入文本，输出 { action, domain, confidence }
 *   - 基于确定性正则 + 加权评分，不依赖运行时 AI
 *   - 信号词和优先级规则均基于 2716 条真实工单数据验证
 *   - 新增 action/domain 只需加一条信号规则，不改优先级逻辑
 */

