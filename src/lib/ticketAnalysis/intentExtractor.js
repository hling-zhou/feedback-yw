const ACTION_TO_SCENE = {
  '资源操作': '资源操作申请',
  '故障排查': '报障与排错',
  '信息咨询': '产品信息咨询',
  '方案设计': '方案咨询与设计',
  '变更调整': '资源操作申请',
  '进度催办': '进度催办与协同',
  '服务投诉': '服务申诉与投诉',
  '费用处理': '费用与账务',
}

// ============================================================
// 主函数
// ============================================================

/**
 * 提取意图：从客户请求文本中提取动作意图和问题域
 *
 * @param {string} text - customerRequest 文本（客户原声）
 * @returns {{ action: string, domain: string, confidence: 'high'|'medium'|'low' }}
 */
export function extractIntent(text) {
  const t = (text || '').trim()
  if (!t) return { action: '其他', domain: '其他', confidence: 'low' }

  const action = extractAction(t)
  const domain = extractDomain(t)
  const confidence = calcConfidence(action, domain, t)

  return { action, domain, confidence }
}

/**
 * 从意图映射到 requestScene
 */
export function intentToRequestScene(action) {
  return ACTION_TO_SCENE[action] || '产品信息咨询'
}

/**
 * 从意图映射到 problemType（domain 直接作为 problemType）
 * 如果 domain 不在预期集合中，兜底为 "其他"
 */
export function intentToProblemType(domain) {
  const valid = DOMAIN_SIGNALS.map(d => d.domain)
  return valid.includes(domain) ? domain : '其他'
}

// ============================================================
// 内部：动作意图提取
// ============================================================

function extractAction(text) {
  // 1. 资源操作（申请+资源名词/移机/续订）—— 最强信号，优先判定
  if (APPLY_RESOURCE_RE.test(text)) return '资源操作'

  // 1b. 移机/施工/续订/续约 属于资源操作——但如果同时有故障症状/排查信号，降级让故障优先
  if (/移机|施工|续订|续签|续约/.test(text) && !FAULT_SYMPTOM_RE.test(text) && !INVESTIGATE_RE.test(text)) return '资源操作'

  // 2. 资源退订/释放
  if (RELEASE_RESOURCE_RE.test(text)) return '资源操作'

  // 3. 投诉
  if (COMPLAINT_RE.test(text)) return '服务投诉'

  // 3b. 费用处理——出账/计费/折扣/索赔等费用类工单优先于催办和故障排查
  //     避免"排查出账问题"被误判为故障排查
  if (BILLING_RE.test(text)) return '费用处理'

  // 4. 催办
  if (URGE_RE.test(text)) return '进度催办'

  // 5. 变更
  if (CHANGE_RE.test(text)) return '变更调整'

  // 6. 咨询 — 要在故障之前判定，因为"如何排查XXX"是咨询不是故障
  if (CONSULT_RE.test(text)) return '信息咨询'

  // 7. 显式排查意图
  if (INVESTIGATE_RE.test(text)) return '故障排查'

  // 8. 故障症状
  if (FAULT_SYMPTOM_RE.test(text)) return '故障排查'

  // 8b. 操作困难/操作失败——客户操作不成功（区别于"如何操作"咨询）
  //     必须在 CONSULT 之后、兜底之前，因为"如何解绑"是咨询，"无法解绑"是故障
  if (OPERATION_DIFFICULTY_RE.test(text)) return '故障排查'

  // 9. 轻微排查请求 — 如果前面都没命中，看是否有"请协助/请帮忙"
  if (LIGHT_INVESTIGATE_RE.test(text)) return '故障排查'

  // 10. 兜底：如果文本提到"申请"但没命中资源名词，仍可能是资源操作
  if (/申请|订购|开通|创建/.test(text)) return '资源操作'

  return '其他'
}

// ============================================================
// 内部：问题域提取
// ============================================================

function extractDomain(text) {
  let bestDomain = '其他'
  let bestScore = 0

  for (const { domain, re, weight } of DOMAIN_SIGNALS) {
    const matches = (text.match(re) || []).length
    const score = matches * weight
    if (score > bestScore) {
      bestScore = score
      bestDomain = domain
    }
  }

  return bestDomain
}

// ============================================================
// 内部：置信度
// ============================================================

function calcConfidence(action, domain, text) {
  if (action === '其他' && domain === '其他') return 'low'
  if (action === '其他' || domain === '其他') return 'medium'
  // 两个维度都有明确信号
  return 'high'
}