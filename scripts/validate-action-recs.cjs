// 某字段出现频次最高的首句（摘要用；非建议）
function topSentence(rows, field) {
  const k = topK(rows, field, 1);
  return k.length ? k[0].s : '';
}
function topK(rows, field, k) {
  const c = {};
  for (const r of rows) {
    const a = firstSentence(get(r, field));
    if (a) c[a] = (c[a] || 0) + 1;
  }
  return Object.entries(c).sort((a, b) => b[1] - a[1]).slice(0, k).map(([s, n]) => ({ s, n }));
}

