/* =========================================================================
 * 发布前自动门禁（preflight）+ 自适应闭环
 * -------------------------------------------------------------------------
 * 把「每期复核清单」脚本化：跑完即出 PASS/FAIL，不依赖人工逐项核对。
 * PREFLIGHT=0 关闭；GATE_STRICT=1 时闭环末端任一 FAIL 以退出码 2 结束（可接 CI 阻断发布）。
 *
 * 自适应闭环（门禁不过→修根因→复跑→过则发，否则升级人工）：
 *   · 修根因 = 只改「分类机制自身的知识资产」（CAUSE_TAX_MAP 家族/子议题正则、autoSplit 提案、新产品派生草稿），
 *     绝不写回 records 任何字段（问题原因等只读）。
 *   · 失败项分两类：① 数据级（解析·*，如缺工单号/月份覆盖不足）→ 机制修不了 → 立即升级人工；
 *     ② 机制可自愈（未归类/待确认/小而锐等）→ 把本期 autoSplit 提案正则补进对应 curated 家族 → 复跑。
 *   · 有上限（GATE_MAX_ATTEMPTS 默认 3）、每轮打印"修了什么"（fixLog）；达上限或无新补丁可应用 → 升级人工，不发布。
 *   · 新产品（无 curated 分类法）派生草稿后，门禁据此判 FAIL·待确认 → 不自动注册 → 升级人工审核后注册。
 * ========================================================================= */

// 门禁：纯计算 + 打印，不退出。返回 { G, fails, warns }。
function runGate(summary) {
  const G = [];
  const push = (name, ok, detail, level) => G.push({ name, ok, detail, level: level || (ok ? 'PASS' : 'FAIL') });

  // 1) 解析完整性
  const unparsed = DATA_META.filter(m => !m.src || !m.month);
  push('解析·sheet维度', unparsed.length === 0,
    unparsed.length ? `${unparsed.length} 个 sheet 未解析出来源/月份：${unparsed.map(m => m.sheet).join('、')}`
                    : `${DATA_META.length} 个 sheet 均解析出「来源+月份」`);
  const emptySheets = DATA_META.filter(m => m.rows === 0);
  push('解析·非空', emptySheets.length === 0 && d.length > 0,
    emptySheets.length ? `空 sheet：${emptySheets.map(m => m.sheet).join('、')}` : `共 ${d.length} 行，${DATA_META.length} 个 sheet 均非空`);
  const months = [...new Set(d.map(r => monthOf(r)).filter(m => m && m !== '?'))].sort();
  push('解析·月份覆盖', months.length >= 2, `月份 ${months.join('、') || '无'}（需 ≥2 个月才能算环比）`);
  const srcs = [...new Set(d.map(r => get(r, '_src')).filter(Boolean))];
  push('解析·来源类型', srcs.length >= 2, `来源 ${srcs.join('、') || '无'}（需同时含投诉与咨询）`);
  const noId = d.filter(r => !get(r, '工单号')).length;
  push('解析·工单号', noId === 0, `缺工单号 ${noId} 行`);
  const noProd = d.filter(r => !get(r, '产品名称')).length;
  push('解析·产品名称', noProd === 0, `缺产品名称 ${noProd} 行`);

  // 2) 未归类率 <5%（阈值可覆盖；新产品派生草稿会显著偏高，门禁据此标 [派生草稿·待确认]）
  const MAX_UNC = +(process.env.GATE_MAX_UNCLASSIFIED || 5);
  const MAX_PEND = +(process.env.GATE_MAX_PENDING || 20);
  for (const s of summary) {
    const rate = s.unclassified / s.T * 100;
    push(`未归类率·${s.p}`, rate < MAX_UNC, `${rate.toFixed(1)}%（阈值 <${MAX_UNC}%）${s.derived ? ' [派生草稿·待确认]' : ''}`);
  }
  // 3) 待确认率（超阈值说明分类法退化或数据质量恶化）
  for (const s of summary) {
    if (s.pending == null) continue;
    const rate = s.pending / s.T * 100;
    push(`待确认率·${s.p}`, rate < MAX_PEND, `${rate.toFixed(1)}%（阈值 <${MAX_PEND}%）${s.derived ? ' [派生草稿·待确认]' : ''}`);
  }
  // 4) 小而锐最小样本 n>=3
  for (const s of summary) {
    const bad = (s.items || []).filter(i => i.tier === 'sharp' && i.n < 3);
    push(`小而锐样本·${s.p}`, bad.length === 0,
      bad.length ? `${bad.length} 项 n<3：${bad.slice(0, 3).map(i => `${i.sub}(${i.n})`).join('、')}` : '均满足 n≥3');
  }
  // 5) 横切项必须单列，不得混入 5 层
  const TIERS5 = ['structural', 'change', 'sharp', 'iteration', 'tail'];
  for (const s of summary) {
    const bad = (s.items || []).filter(i => i.crossCut && TIERS5.includes(i.tier));
    push(`横切项单列·${s.p}`, bad.length === 0, bad.length ? `${bad.length} 个横切项混入 5 层` : '横切项已单列');
  }
  // 6) 出处标注：分析层字段须显式标注，不得裸引冒充客户原话
  for (const s of summary) {
    let txt = '';
    try { txt = fs.readFileSync(path.join(DOCS, `行动建议-${s.p}-验证.md`), 'utf8'); } catch { /* noop */ }
    const ok = txt.includes('〔痛点摘要〕') || txt.includes('〔复核根因〕');
    push(`出处标注·${s.p}`, ok, ok ? '已标注〔痛点摘要〕/〔复核根因〕' : '未检出分析层标注，疑似裸引');
  }

  const fails = G.filter(g => g.level === 'FAIL');
  const warns = G.filter(g => g.level === 'WARN');
  console.log('\n===== 发布前自动门禁（preflight）=====');
  for (const g of G) console.log(`  [${g.level}] ${g.name} — ${g.detail}`);
  console.log(`  ---- PASS ${G.filter(g => g.level === 'PASS').length} / WARN ${warns.length} / FAIL ${fails.length} ----`);
  return { G, fails, warns };
}

// 新产品无 curated 分类法时，复用"原因优先"挖掘为该产品派生专属原因家族草稿。
// 机制适配（非通用兜底、非跳过）：从该产品自身 问题原因/需求痛点 挖最高频问题短语作家族种子。
// 产出 TAX 同构对象（derived:true）。草稿不自动注册进 CAUSE_TAX_MAP（保可监督）；门禁据 derived 标·待确认→升级人工。
function deriveDraftTax(product, rows) {
  const S = '';
  const texts = rows.map(r => [get(r, '问题原因'), get(r, '需求痛点')].filter(Boolean).join(S));
  const cand = new Map();
  const minDf = Math.max(2, Math.ceil(0.03 * rows.length));
  for (const t of texts) {
    for (let len = 3; len <= 10; len++) {
      for (let i = 0; i + len <= t.length; i++) {
        const q = t.slice(i, i + len);
        if (q.indexOf(S) >= 0) continue;
        if (!/^[一-龥]/.test(q) || !PROBLEM_CUE.test(q)) continue;
        const nonCue = q.replace(PROBLEM_CUE, '');
        if ((nonCue.match(/[一-龥]/g) || []).length < 2) continue;
        if (/[的了和与或在是为无有未不此于对至向等中时后前内外上下该其之]$/.test(q)) continue;
        cand.set(q, (cand.get(q) || 0) + 1);
      }
    }
  }
  const ranked = [...cand.entries()].filter(([, c]) => c >= minDf).sort((a, b) => b[1] - a[1]);
  const chosen = [];
  for (const [q, c] of ranked) {
    if (chosen.length >= 10) break;
    if (chosen.some(([q2]) => q2.includes(q) || q.includes(q2))) continue; // 去互相包含
    chosen.push([q, c]);
  }
  const families = chosen.map(([q], idx) => ({ key: 'draft_' + idx, name: q, re: new RegExp(q), subs: [] }));
  if (!families.length) families.push({ key: 'draft_other', name: '待归类(草稿)', re: /.*/, subs: [] });
  return { name: `${product}·派生草稿`, derived: true, families };
}

// 深克隆一份分类法（重建 RegExp），使自适应闭环每轮从"干净的 curated 克隆 + 累计补丁"重建，
// 绝不改动全局 CAUSE_TAX_MAP（避免跨轮次污染、保证每轮独立可复现）。
function cloneTax(tax) {
  return {
    name: tax.name, derived: !!tax.derived,
    families: tax.families.map(f => ({
      key: f.key, name: f.name, re: new RegExp(f.re.source, f.re.flags), crossCut: f.crossCut,
      subs: (f.subs || []).map(s => ({ key: s.key, name: s.name, re: new RegExp(s.re.source, s.re.flags) })),
    })),
  };
}

// 自适应闭环：门禁不过→修根因（仅改分类机制，不动 records）→复跑→过则发；否则升级人工。
function runAdaptiveLoop() {
  if (process.env.PREFLIGHT === '0') {
    runPipeline();
    console.log('[PREFLIGHT=0] 门禁已关闭，仅产出报告');
    return;
  }
  const MAX = Math.max(1, +(process.env.GATE_MAX_ATTEMPTS || 3));
  const fixLog = [];           // 每轮可见的诊断轨迹（可监督）
  let lastGate = null, success = false;
  for (let attempt = 1; attempt <= MAX; attempt++) {
    // 每轮用干净的 curated 分类法（克隆，绝不回写全局 CAUSE_TAX_MAP）跑一遍。
    // ⚠️ 关键纪律：不在闭环里自动把 autoSplit 子议题提案回写分类法——
    // 因为 learnWordWeights 会把子议题正则纳入词权重自举学习（见 1216 行 famSeedMatchers），
    // 回写即"重训整个打分模型"，会让 conf/阈值漂移、待确认率不可复现（实测 10.7%→20%）。
    // 真正的"修根因"（人工补 curated 正则 / 注册派生草稿）是人工步骤，由下方升级报告明确列出。
    const eff = {};
    for (const p of Object.keys(CAUSE_TAX_MAP)) eff[p] = cloneTax(CAUSE_TAX_MAP[p]);
    runPipeline(eff);
    const gate = runGate(summary);
    lastGate = gate;
    if (gate.fails.length === 0) { success = true; break; }
    fixLog.push(`[尝试 ${attempt}] 门禁 FAIL ${gate.fails.length} 项`);
    // 失败项分类：① 数据级（解析·*）→ 机制修不了；② 其余 → 人工修根因（见升级报告）
    const fatal = gate.fails.filter(f => f.name.startsWith('解析'));
    if (fatal.length) {
      fixLog.push(`  · 数据级失败，需查源数据：${fatal.map(f => f.name).join('、')}`);
      break;
    }
    // 无安全可自动修复项 → 诚实升级（不无限循环、不靠放宽阈值蒙混）
    break;
  }
  console.log('\n===== 自适应闭环结论 =====');
  if (success) {
    console.log(`[OK] 门禁通过（${lastGate.G.length - lastGate.fails.length}/${lastGate.G.length} PASS），可发布。`);
    if (fixLog.length) { console.log('  自愈轨迹：'); fixLog.forEach(l => console.log('   ' + l)); }
  } else {
    const derivedProds = summary.filter(s => s.derived).map(s => s.p);
    console.log('[ESCALATE] 门禁未通过，需人工介入（不发布）。门禁只拦不修——以下为「需人工修根因」清单：');
    for (const f of lastGate.fails) {
      const prod = (f.name.split('·')[1] || '').replace(/^未归类率|待确认率|小而锐样本|横切项单列|出处标注/, '').trim();
      if (f.name.startsWith('解析')) {
        console.log(`   [数据级] ${f.name}: ${f.detail} → 查源数据/入库质量，机制无法自动修`);
      } else if (derivedProds.includes(prod)) {
        console.log(`   [派生草稿] ${f.name}: ${f.detail} → 机制已为该新产品派生专属原因家族草稿，请人工审核后注册为 curated 分类法（docs/L2自动细分-提案.md 可参考）`);
      } else {
        console.log(`   [需补正则] ${f.name}: ${f.detail} → 人工补该产品的 curated 正则/子议题（参考自动生成的 docs/L2自动细分-提案.md 与 dist/audit_sample.md）`);
      }
    }
    if (fixLog.length) { console.log('   诊断轨迹：'); fixLog.forEach(l => console.log('   ' + l)); }
    console.log('   说明：闭环不自动把 autoSplit 提案回写分类法（会重训词权重模型致漂移），故 FAIL 一律升级人工，不发布。');
    if (process.env.GATE_STRICT) process.exit(2);
  }
}
