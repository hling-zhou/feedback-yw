    thresholds: { H: s.thr.H, S: s.thr.S, L: s.thr.L, delta: s.thr.delta },
    items: (s.items || []).map(it => ({ fam: it.fam, sub: it.sub, tier: it.tier, n: it.n, cr: it.cr, mom: it.mom, dAbs: it.dAbs, crossCut: !!it.crossCut })),
    matchStats: s.matchStats,
